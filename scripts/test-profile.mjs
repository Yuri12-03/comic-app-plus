import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync("src/lib/profile.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports });
assert.equal(exports.avatarPresets.length, 8);
assert.equal(new Set(exports.avatarPresets.map(item => item.id)).size, 8);
assert.equal(exports.validDisplayName("漫画好きのねこ"), true);
assert.equal(exports.validDisplayName("😀".repeat(30)), true);
assert.equal(exports.validDisplayName("😀".repeat(31)), false);
assert.equal(exports.validDisplayName(""), false);
assert.equal(exports.validDisplayName("bad\nname"), false);
assert.equal(exports.isAvatarPreset("cat"), true);
assert.equal(exports.isAvatarPreset("../../another-user/photo"), false);
assert.equal(exports.imageContentType(Uint8Array.from([255,216,255,224])), "image/jpeg");
assert.equal(exports.imageContentType(Uint8Array.from([137,80,78,71,13,10,26,10])), "image/png");
assert.equal(exports.imageContentType(new TextEncoder().encode("RIFF0000WEBP")), "image/webp");
assert.equal(exports.imageContentType(new TextEncoder().encode('<svg onload="alert(1)">')), null);
assert.equal(exports.imageContentType(new Uint8Array()), null);
console.log("Profile names, presets and image signatures passed");
