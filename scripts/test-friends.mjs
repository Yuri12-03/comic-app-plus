assert.equal(exports.friendReturnPath(`/account/friends/add?code=${code}`),`/account/friends/add?code=${code}`);
assert.equal(exports.friendReturnPath("/account/friends/add?code=invalid"),null);
const qr=QRCode.create(link,{errorCorrectionLevel:"M"});const scale=8,margin=4,width=(qr.modules.size+margin*2)*scale;const luminances=new Uint8ClampedArray(width*width).fill(255);
for(let y=0;y<qr.modules.size;y++)for(let x=0;x<qr.modules.size;x++)if(qr.modules.get(y,x))for(let dy=0;dy<scale;dy++)for(let dx=0;dx<scale;dx++)luminances[((y+margin)*scale+dy)*width+(x+margin)*scale+dx]=0;
const decoded=new QRCodeReader().decode(new BinaryBitmap(new HybridBinarizer(new RGBLuminanceSource(luminances,width,width)))).getText();
assert.equal(decoded,link);assert.equal(exports.parseFriendQr(decoded),code);
