import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
import vm from "node:vm";
import QRCode from "qrcode";
import { QRCodeReader, RGBLuminanceSource, BinaryBitmap, HybridBinarizer } from "@zxing/library";
const exports={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync("src/lib/friends.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,URL});
const code="ABCDEF0123456789", link=`https://comic-app-plus.vercel.app/account/friends/add?code=${code}`;
assert.equal(exports.normalizeFriendCode("ａｂｃｄ-ｅｆ０１-２３４５-６７８９"),code);
assert.equal(exports.normalizeFriendCode("1234"),null);
assert.equal(exports.parseFriendQr(link),code);
assert.equal(exports.parseFriendQr(`https://evil.example/account/friends/add?code=${code}`),null);
assert.equal(exports.parseFriendQr(`https://comic-app-plus.vercel.app@evil.example/account/friends/add?code=${code}`),null);
